create table if not exists public.site_settings (
  id integer primary key default 1 check (id = 1),
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null default 'নাম প্রকাশে অনিচ্ছুক',
  review_text text not null,
  image_url text,
  approved boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.site_settings enable row level security;
alter table public.reviews enable row level security;

-- Public can read published settings and approved reviews only.
drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings" on public.site_settings
for select to anon, authenticated using (true);

drop policy if exists "Admins manage site settings" on public.site_settings;
create policy "Admins manage site settings" on public.site_settings
for all to authenticated using (true) with check (true);

drop policy if exists "Public can read approved reviews" on public.reviews;
create policy "Public can read approved reviews" on public.reviews
for select to anon, authenticated using (approved = true);

drop policy if exists "Visitors can submit reviews" on public.reviews;
create policy "Visitors can submit reviews" on public.reviews
for insert to anon, authenticated with check (approved = false);

drop policy if exists "Admins manage reviews" on public.reviews;
create policy "Admins manage reviews" on public.reviews
for all to authenticated using (true) with check (true);

-- Create a public image bucket. Uploaded review photos are displayed only
-- when their review is approved. Do not upload private or sensitive images.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('site-images', 'site-images', true, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do nothing;

drop policy if exists "Public read site images" on storage.objects;
create policy "Public read site images" on storage.objects
for select to anon, authenticated using (bucket_id = 'site-images');

drop policy if exists "Visitors upload images" on storage.objects;
create policy "Visitors upload images" on storage.objects
for insert to anon, authenticated with check (bucket_id = 'site-images');

drop policy if exists "Authenticated users update images" on storage.objects;
create policy "Authenticated users update images" on storage.objects
for update to authenticated using (bucket_id = 'site-images') with check (bucket_id = 'site-images');

drop policy if exists "Authenticated users delete images" on storage.objects;
create policy "Authenticated users delete images" on storage.objects
for delete to authenticated using (bucket_id = 'site-images');

-- Enable realtime updates.
alter publication supabase_realtime add table public.site_settings;
alter publication supabase_realtime add table public.reviews;
